from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from .finder import SharedVariable, find_shared_variables, dump_shared_variables, instrument_code


def _format_variable(variable: SharedVariable) -> str:
    return f"{variable.file}:{variable.line} [{variable.kind}] {variable.name} -> {variable.declaration}"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Identify shared variables in C/C++ source files.")
    parser.add_argument("paths", nargs="+", help="Files or directories to scan")
    parser.add_argument(
        "-r", "--recursive", action="store_true", default=False,
        help="Recursively scan directories")
    parser.add_argument(
        "--json", action="store_true", default=False,
        help="Output results as JSON")
    parser.add_argument(
        "--instrument", action="store_true", default=False,
        help="Instrument code with SIM_FLUSH calls for shared variables")
    parser.add_argument(
        "-I", "--include", action="append", default=[],
        help="Add an include directory for Clang AST parsing")
    parser.add_argument(
        "--conservative-ptr", action="store_true", default=False,
        help="Treat all pointer-typed function parameters as potential shared variables")
    parser.add_argument(
        "--post-if-flush", action="store_true", default=False,
        help="Insert a SIM_FLUSH after every if/else-if/else chain")
    parser.add_argument(
        "--bitfield-map", default=None,
        help="Path to JSON bitfield map file (skip bit-field members that cannot take address)")
    parser.add_argument(
        "--struct-header", default=None,
        help="Path to consolidated struct header (generated by collect.py --output-header), force-included during AST parsing for better type resolution")
    parser.add_argument(
        "--temp-flush", action="store_true", default=False,
        help="Enable source-level fallback: scan for shared variable member accesses missed by clang, instrument with SIM_FLUSH_TEMP")
    args = parser.parse_args(argv)

    if args.instrument:
        if len(args.paths) != 1:
            print("Error: --instrument requires exactly one file path")
            return 1
        path = Path(args.paths[0])
        if not path.is_file():
            print(f"Error: {path} is not a file")
            return 1
        try:
            source = path.read_text(encoding="utf-8")
        except OSError as e:
            print(f"Error reading file: {e}")
            return 1
        instrumented = instrument_code(source, str(path), path, include_paths=args.include, conservative_ptr=args.conservative_ptr, post_if_flush=args.post_if_flush, bitfield_map_path=args.bitfield_map, struct_header_path=args.struct_header, temp_flush=args.temp_flush)
        output_path = path.with_name(f"{path.stem}_result{path.suffix}")
        try:
            output_path.write_text(instrumented, encoding="utf-8")
        except OSError as e:
            print(f"Error writing output file: {e}")
            return 1
        print(f"Instrumented output written to: {output_path}")
        return 0

    variables = find_shared_variables(args.paths, recursive=args.recursive)
    if args.json:
        print(dump_shared_variables(variables))
        return 0

    if not variables:
        print("No shared variables found.")
        return 0

    for variable in variables:
        print(_format_variable(variable))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
